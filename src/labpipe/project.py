"""Projects: `labpipe project new | sync` (docs/design/install.md → Code and projects).

A project is a folder with `labpipe.yaml`: the user's data paths, settings, context, results
and the lab's own additions (`lab/`). The code (defaults, docs, agent roles, …) lives
elsewhere (`safety.CODE_ROOT`) and is replaced by updates; the project is never written by
one. What the agents read of the code is copied into the project by `project sync`, as
generated files that begin with a "Generated by labpipe" line:

    AGENTS.md, CLAUDE.md      the code's text + "This lab's additions" (lab/LAB.md)
    .labpipe/                 docs/, config/ (defaults), methods.yaml, references/, agents/,
                              hooks/guard.py, generated.json (what was generated, from what)
    .claude/*.json, .codex/   permissions and hook of the harness, adapted to the project
    .claude/agents/ …         the harness's agent files (`agents.py`, with the lab's overlays)

In dev mode (the repository is its own project) the tracked sources are the files themselves:
`project sync` then only writes the harness's agent files, as `agents sync` always did.
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path
from typing import Any

import yaml

from labpipe import __version__, agents
from labpipe.provenance import utc_now
from labpipe.safety import (CODE_ROOT, FIXED_GENERATED, GENERATED_DIR, GENERATED_RECORD, PROJECT_FILE, PROJECT_ROOT, atomic_write_bytes,
                            atomic_write_text, default_config_files, find_project, is_dev,
                            load_pipeline_config, synced_marker)

SCHEMA = "labpipe.project/1"
GENERATED = GENERATED_RECORD
GENERATED_SCHEMA = "labpipe.generated/1"
LAB_FILE = "lab/LAB.md"
ADDITIONS = "## This lab's additions (lab/LAB.md)"
README_TEXT = """\
Generated by labpipe {version}. Do not edit: `labpipe project sync` rewrites everything here.

A read-only copy of what the agents read of labpipe's code: `docs/`, `config/` (the defaults),
`methods.yaml`, `references/`, `agents/` (the roles). Your own files are outside this folder:
`config/` (settings), `lab/LAB.md` and `lab/agents/` (instructions for the agents).
"""
# Rules added to the generated harness permissions (only the project copy; the repository's
# own files stay as they are for people who develop labpipe).
CLAUDE_DENY = ["Edit(/.labpipe/**)", "Edit(/AGENTS.md)", "Edit(/CLAUDE.md)"]
CLAUDE_ASK = ["Edit(/lab/**)", "Edit(/labpipe.yaml)"]
UNATTENDED_DENY = ["Edit(**/.labpipe/**)", "Edit(**/AGENTS.md)", "Edit(**/CLAUDE.md)",
                   "Edit(**/lab/**)", "Edit(**/labpipe.yaml)"]
# The hook finds the project by walking up from the harness's folder to labpipe.yaml.
CODEX_HOOK = ('d="$PWD"; while [ ! -f "$d/labpipe.yaml" ] && [ "$d" != / ]; do '
              'd=$(dirname "$d"); done; python3 "$d/.labpipe/hooks/guard.py"')


class ProjectError(RuntimeError):
    pass


# ---- reading a project -------------------------------------------------------------------

def read_project(project: Path | None = None) -> dict[str, Any]:
    """labpipe.yaml of the project ({} in dev mode or if unreadable)."""
    try:
        data = yaml.safe_load((Path(project or PROJECT_ROOT) / PROJECT_FILE).read_text(
            encoding="utf-8"))
    except (OSError, yaml.YAMLError):
        return {}
    return data if isinstance(data, dict) else {}


def project_name(project: Path | None = None) -> str:
    project = Path(project or PROJECT_ROOT)
    return str(read_project(project).get("name") or project.resolve().name)


def slug(text: str) -> str:
    """Letters, digits and '-' only (container names, volumes)."""
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "project"


# ---- the generated files -----------------------------------------------------------------

def _comment(text: str, style: str) -> str:
    return f"<!-- {text} -->\n\n" if style == "md" else f"# {text}\n\n"


def _header(source: str) -> str:
    return (f"Generated by labpipe {__version__} from {source}. Do not edit; your additions "
            "go in lab/LAB.md (or lab/agents/)")


def _with_additions(source: str, project: Path) -> bytes:
    text = agents.readable_code_paths((CODE_ROOT / source).read_text(encoding="utf-8"))
    try:
        lab = agents.without_comments((project / LAB_FILE).read_text(encoding="utf-8"))
        if all(line.startswith("#") for line in lab.splitlines() if line.strip()):
            lab = ""         # only the template's heading: nothing written yet
    except OSError:
        lab = ""
    section = f"\n\n{ADDITIONS}\n\n{lab or '(nothing yet)'}\n"
    return (_comment(_header(source), "md") + text.rstrip("\n") + section).encode("utf-8")


def _json_bytes(data: Any) -> bytes:
    return (json.dumps(data, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def _claude_settings(name: str) -> bytes:
    data = json.loads((CODE_ROOT / ".claude" / name).read_text(encoding="utf-8"))
    permissions = data.setdefault("permissions", {})
    if name == "settings.json":
        permissions["deny"] = [*permissions.get("deny", []), *CLAUDE_DENY]
        permissions["ask"] = [*permissions.get("ask", []), *CLAUDE_ASK]
        for group in data.get("hooks", {}).get("PreToolUse", []):
            for hook in group.get("hooks", []):
                hook["command"] = hook["command"].replace("/hooks/guard.py",
                                                          "/.labpipe/hooks/guard.py")
    else:
        permissions["deny"] = [*permissions.get("deny", []), *UNATTENDED_DENY]
    return _json_bytes(data)


def _codex_file(path: Path) -> bytes:
    relative = path.relative_to(CODE_ROOT / ".codex").as_posix()
    text = path.read_text(encoding="utf-8")
    if relative == "hooks.json":
        data = json.loads(text)
        for group in data["hooks"]["PreToolUse"]:
            for hook in group["hooks"]:
                hook["command"] = CODEX_HOOK
        return _json_bytes(data)
    return (_comment(_header(f".codex/{relative}"), "#") + text).encode("utf-8")


def _tree(source: Path, target: str, out: dict[str, bytes]) -> None:
    if source.is_dir():
        for path in sorted(p for p in source.rglob("*") if p.is_file()
                           and "__pycache__" not in p.parts and p.name != ".DS_Store"):
            out[f"{target}/{path.relative_to(source).as_posix()}"] = path.read_bytes()


def desired_files(project: Path) -> dict[str, bytes]:
    """Every generated file except the harness's agent files: path (relative to the project)
    → content. Pure: reads the code and the lab's own files, writes nothing."""
    files: dict[str, bytes] = {}
    for name in FIXED_GENERATED:
        files[name] = _with_additions(name, project)
    files[f"{GENERATED_DIR}/README.md"] = README_TEXT.format(version=__version__).encode()
    for folder in ("docs", "references", "agents"):
        _tree(CODE_ROOT / folder, f"{GENERATED_DIR}/{folder}", files)
    for path in default_config_files():
        files[f"{GENERATED_DIR}/config/{path.name}"] = path.read_bytes()
    files[f"{GENERATED_DIR}/methods.yaml"] = (CODE_ROOT / "methods.yaml").read_bytes()
    files[f"{GENERATED_DIR}/hooks/guard.py"] = (CODE_ROOT / "hooks" / "guard.py").read_bytes()
    for name in ("settings.json", "unattended.json", "unattended-container.json"):
        if (CODE_ROOT / ".claude" / name).exists():
            files[f".claude/{name}"] = _claude_settings(name)
    skills = CODE_ROOT / ".agents"            # Codex skills; they name `agents/…` too
    for path in sorted(p for p in skills.rglob("*") if p.is_file()) if skills.is_dir() else []:
        text = path.read_text(encoding="utf-8")
        files[f".agents/{path.relative_to(skills).as_posix()}"] = agents.readable_code_paths(
            text).encode("utf-8")
    codex = CODE_ROOT / ".codex"
    for path in sorted(p for p in codex.rglob("*") if p.is_file()
                       and p.relative_to(codex).parts[0] != "agents") if codex.is_dir() else []:
        files[f".codex/{path.relative_to(codex).as_posix()}"] = _codex_file(path)
    return files


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sources_hash(files: dict[str, bytes]) -> str:
    return _sha(json.dumps({path: _sha(data) for path, data in sorted(files.items())},
                           sort_keys=True).encode())


def _recorded(project: Path) -> dict[str, Any]:
    try:
        data = json.loads((project / GENERATED).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def generated_paths(project: Path | None = None) -> set[str]:
    """Relative paths of every file labpipe generated in the project (for the guard)."""
    return set((_recorded(Path(project or PROJECT_ROOT)).get("files") or {}))


def sync(project: Path | None = None, config: dict | None = None) -> dict[str, Any]:
    """Write the generated files and the harness's agent files. Idempotent."""
    project = Path(project or PROJECT_ROOT)
    if config is None:
        config = load_pipeline_config(None if project == PROJECT_ROOT else project)
    if is_dev(project):
        try:
            result = agents.sync(config, project)
        except agents.AgentConfigError as exc:
            return {"mode": "dev", "error": str(exc)}
        return {"mode": "dev", **result, "note": "the repository is its own project: "
                "AGENTS.md, CLAUDE.md, docs/ and .claude/ are the sources and are not rewritten"}
    files = desired_files(project)
    written, problems = [], []
    for path, data in files.items():
        target = project / path
        if not target.exists() or target.read_bytes() != data:
            atomic_write_bytes(target, data, config, pipeline=False)
            written.append(path)
    agent_result: dict[str, Any] | None = None
    try:
        agent_result = agents.sync(config, project)
        problems += agent_result["problems"]
    except agents.AgentConfigError as exc:
        problems.append(f"agents: {exc}")
    agent_files = [row["file"] for row in (agent_result or {}).get("written", [])]
    previous = set(_recorded(project).get("files") or {})
    removed = []
    for stale in sorted(previous - set(files) - set(agent_files)):
        target = project / stale
        if target.is_file() and target.resolve().is_relative_to(project.resolve()):
            target.unlink()          # only what labpipe itself generated before
            removed.append(stale)
    recorded = {path: _sha(data) for path, data in files.items()}
    recorded |= {path: _sha((project / path).read_bytes()) for path in agent_files}
    record = {"schema": GENERATED_SCHEMA, "labpipe_version": __version__,
              "sources_sha256": sources_hash(files), "files": dict(sorted(recorded.items()))}
    atomic_write_bytes(project / GENERATED, _json_bytes(record), config, pipeline=False)
    return {"mode": "project", "project": str(project), "written": written, "removed": removed,
            "unchanged": len(files) - len(written), "agents": agent_result,
            "problems": problems}


def status(project: Path | None = None) -> dict[str, Any]:
    """For doctor: the project, its mode, and whether the generated files are current."""
    project = Path(project or PROJECT_ROOT)
    info = {"path": str(project), "name": project_name(project)}
    if is_dev(project):
        return {**info, "mode": "dev", "generated": None}
    files = desired_files(project)
    recorded = _recorded(project)
    have = recorded.get("files") or {}
    missing = sorted(p for p in files if not (project / p).exists())
    edited = sorted(p for p, digest in have.items()
                    if (project / p).is_file() and _sha((project / p).read_bytes()) != digest)
    current = (recorded.get("sources_sha256") == sources_hash(files) and not missing
               and not edited)
    return {**info, "mode": "project", "labpipe_version": recorded.get("labpipe_version"),
            "generated": {"current": current, "missing": missing, "edited": edited,
                          "sources_changed": recorded.get("sources_sha256")
                          != sources_hash(files)}}


# ---- `project new` -----------------------------------------------------------------------

def user_defaults_file() -> Path:
    """This user's defaults for new projects (the installer writes it)."""
    return Path.home() / ".config" / "labpipe" / "defaults.yaml"


def _agents_block() -> dict[str, Any]:
    try:
        block = (yaml.safe_load(user_defaults_file().read_text(encoding="utf-8")) or {}).get(
            "agents")
    except (OSError, yaml.YAMLError):
        block = None
    if isinstance(block, dict) and block:
        return block
    example = yaml.safe_load((CODE_ROOT / "config" / "local.example.yaml").read_text(
        encoding="utf-8"))
    return example["agents"]


def _root_id(folder: Path, taken: set[str]) -> str:
    base = re.sub(r"[^A-Za-z0-9_.-]+", "_", folder.name).strip("._-") or "data"
    root_id, number = base, 2
    while root_id in taken:
        root_id, number = f"{base}-{number}", number + 1
    taken.add(root_id)
    return root_id


def _local_yaml(data: list[Path]) -> str:
    taken: set[str] = set()
    roots = [{"id": _root_id(folder, taken), "path": folder.as_posix()} for folder in data]
    body = yaml.safe_dump({"raw_roots": roots, "protected_paths": [],
                           "agents": _agents_block()}, sort_keys=False, allow_unicode=True,
                          width=1000)
    return ("# This project on this computer (never shared). Raw data is only read from the\n"
            "# folders in raw_roots. All settings: config/local.example.yaml and docs/settings/.\n"
            + body)


def new(folder: str | Path, data: list[str] | None = None, name: str | None = None
        ) -> dict[str, Any]:
    """Create a project folder, then `project sync` it. Never overwrites a file."""
    project = Path(folder).expanduser().resolve()
    marker = synced_marker(project)
    if marker:
        raise ProjectError(f"{project} is inside a synced folder ({marker}): sync clients "
                           "spread deletions and corrupt state. Choose a local folder, e.g. "
                           "~/labpipe-projects/<name>")
    existing = project.is_dir() and (project / PROJECT_FILE).is_file()
    if project.exists() and not project.is_dir():
        raise ProjectError(f"{project} is a file, not a folder")
    if project.is_dir() and any(project.iterdir()) and not existing:
        raise ProjectError(f"{project} is not empty and is not a labpipe project: choose an "
                           "empty or new folder")
    outer = find_project(project.parent) if not existing else None
    if outer:
        raise ProjectError(f"{project} would be inside the project {outer}: projects do not nest")
    folders = []
    for item in data or []:
        path = Path(item).expanduser().resolve()
        if not path.is_dir():
            raise ProjectError(f"data folder not found: {path}")
        if path == project or path in project.parents:
            raise ProjectError(f"the project folder {project} must not be inside the data "
                               f"folder {path}: labpipe never writes there")
        folders.append(path)
    chosen = name or project.name
    templates = CODE_ROOT / "templates" / "project"
    texts = {
        PROJECT_FILE: yaml.safe_dump({"schema": SCHEMA, "name": chosen,
                                      "created_utc": utc_now(), "labpipe_version": __version__},
                                     sort_keys=False, allow_unicode=True),
        "config/local.yaml": _local_yaml(folders),
        "config/lab.yaml": (CODE_ROOT / "config" / "lab.example.yaml").read_text("utf-8"),
        "config/samples.yaml": (CODE_ROOT / "config" / "samples.example.yaml").read_text("utf-8"),
        LAB_FILE: (templates / "LAB.md").read_text("utf-8"),
        "lab/agents/README.md": (templates / "agents-README.md").read_text("utf-8"),
    }
    project.mkdir(parents=True, exist_ok=True)
    config = {"raw_roots": [{"path": str(f)} for f in folders], "protected_paths": []}
    created, kept = [], []
    for path, text in texts.items():
        if (project / path).exists():
            kept.append(path)
        else:
            atomic_write_text(project / path, text, config, pipeline=False)
            created.append(path)
    synced = sync(project)
    nxt = [f"cd {project}"]
    if not folders:
        nxt.append("labpipe setup --only raw-data   (or put the data folder in "
                   "config/local.yaml → raw_roots)")
    nxt += ["labpipe doctor", "open your agent tool in this folder and say: start"]
    return {"project": str(project), "name": chosen, "created": created, "kept": kept,
            "synced": {k: synced.get(k) for k in ("written", "problems")}, "next": nxt}
