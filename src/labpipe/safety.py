"""Path safety: where the pipeline may write, and atomic writes.

Two roots (docs/design/install.md): CODE_ROOT is the code (defaults, methods.yaml,
references, agents, docs, templates; replaced by updates), PROJECT_ROOT is one project (the
user's settings, context, results; `labpipe.yaml` marks it). With no project around, the
repository is its own project ("dev mode": CODE_ROOT == PROJECT_ROOT).

Rules (enforced here, independent of Claude Code permissions and the OS
read-only mount, which are further layers):
* nothing is ever written inside a raw root or a protected path;
* pipeline writes go only to <project>/analysis, <project>/logs and <project>/manifest.json;
* every write is atomic (temp file in the same directory + os.replace);
* nothing is deleted; superseded outputs are moved within analysis/.
"""

from __future__ import annotations

import os
import tempfile
from pathlib import Path
from typing import Any

import yaml

PROJECT_FILE = "labpipe.yaml"
# Generated by `labpipe project sync`; agents never write them (guard, harness permissions).
GENERATED_DIR = ".labpipe"
GENERATED_RECORD = f"{GENERATED_DIR}/generated.json"
FIXED_GENERATED = ("AGENTS.md", "CLAUDE.md")
# Folders of sync clients (a project must not live in one: they corrupt state and spread deletions).
SYNC_MARKERS = ("koofr", "onedrive", "dropbox", "google drive", "googledrive", "icloud",
                "nextcloud", "owncloud", "syncthing", "mega", "seafile")


def synced_marker(path: Path | str) -> str | None:
    """A path segment named like a sync client's folder (e.g. 'OneDrive - Lab', 'Dropbox')."""
    for part in (p.lower() for p in Path(path).parts):
        for marker in SYNC_MARKERS:
            if part.startswith(marker) and (marker != "mega" or part in ("mega", "megasync")
                                            or part.startswith("megasync")):
                return marker
    return None


def find_project(start: Path | str | None = None) -> Path | None:
    """The nearest folder from `start` (default: the current folder) upwards that holds
    labpipe.yaml, or None."""
    try:
        here = Path(start if start is not None else os.getcwd()).resolve()
    except OSError:
        return None
    for folder in (here, *here.parents):
        if (folder / PROJECT_FILE).is_file():
            return folder
    return None


def install_home() -> Path:
    """The installation folder (app/, venv/): LABPIPE_HOME, else ~/.local/share/labpipe
    (Windows: %LOCALAPPDATA%/labpipe)."""
    chosen = os.environ.get("LABPIPE_HOME")
    if chosen:
        return Path(chosen).expanduser()
    if os.name == "nt":
        return Path(os.environ.get("LOCALAPPDATA") or Path.home() / "AppData" / "Local") / "labpipe"
    return Path.home() / ".local" / "share" / "labpipe"


def config_home() -> Path:
    """This user's labpipe folder for settings that belong to no project (defaults.yaml, the
    container login file): LABPIPE_CONFIG_HOME, else ~/.config/labpipe."""
    chosen = os.environ.get("LABPIPE_CONFIG_HOME")
    return Path(chosen).expanduser() if chosen else Path.home() / ".config" / "labpipe"


def is_installation(code_root: Path) -> bool:
    """Is this code folder an installation (replaced by updates) rather than a repository
    somebody develops in? Marked by `.labpipe-installed` (the installer writes it) or by
    being the installation's own app folder (`install_home()/app`)."""
    if (code_root / ".labpipe-installed").exists():
        return True
    return os.path.realpath(code_root) == os.path.realpath(install_home() / "app")


def optional_install_command(package: str) -> str:
    """The exact command that installs an optional dependency into THIS environment, at the
    version pinned in pyproject.toml (extras). The user runs it; labpipe never does."""
    import re
    import sys
    try:
        text = (CODE_ROOT / "pyproject.toml").read_text(encoding="utf-8")
    except OSError:
        text = ""
    pin = re.search(rf'"({re.escape(package)}==[^"\s]+)"', text)
    return f'"{sys.executable}" -m pip install "{pin.group(1) if pin else package}"'


def _roots() -> tuple[Path, Path, bool]:
    code = Path(os.environ.get("LABPIPE_CODE") or Path(__file__).resolve().parents[2])
    chosen = os.environ.get("LABPIPE_PROJECT") or os.environ.get("LABPIPE_ROOT")
    if chosen:
        return code, Path(chosen), False
    found = find_project()
    if found is not None:
        return code, found, False
    # No project: the repository is its own project (dev mode), unless this is an installation.
    return code, code, is_installation(code)


CODE_ROOT, PROJECT_ROOT, NO_PROJECT = _roots()
NO_PROJECT_MESSAGE = ("not in a labpipe project; create one with `labpipe project new <folder>` "
                      "(then run labpipe inside it)")


def is_dev(project: Path | str) -> bool:
    """Is this project the code folder itself (the repository is its own project)? In the
    container the two are the same bind mount, under different names."""
    try:
        return os.path.samefile(CODE_ROOT, project)
    except OSError:
        return Path(CODE_ROOT) == Path(project)


def dev_mode() -> bool:
    return is_dev(PROJECT_ROOT)


def require_project() -> None:
    if NO_PROJECT:
        raise SetupError(NO_PROJECT_MESSAGE)


class UnsafePathError(RuntimeError):
    pass


class SetupError(RuntimeError):
    pass


def in_container() -> bool:
    return bool(os.environ.get("LABPIPE_IN_CONTAINER"))


def _parse_root_paths(text: str) -> dict[str, str]:
    """LABPIPE_ROOT_PATHS="lab=/data/lab,other=/data/other" -> {id: path}."""
    mapping = {}
    for part in filter(None, (item.strip() for item in text.split(","))):
        root_id, separator, path = part.partition("=")
        if not separator or not root_id.strip() or not path.strip():
            raise SetupError(f"LABPIPE_ROOT_PATHS: cannot read {part!r} (expected id=path)")
        mapping[root_id.strip()] = path.strip()
    return mapping


def _map_root_paths(roots: list[dict], mapping: dict[str, str]) -> list[dict]:
    """Inside the container the raw roots are found by id (read-only mounts)."""
    configured = {root["id"] for root in roots}
    unknown = sorted(set(mapping) - configured)
    missing = sorted(configured - set(mapping))
    if unknown:
        raise SetupError(f"LABPIPE_ROOT_PATHS names raw root(s) {', '.join(unknown)} that are "
                         "not in config/local.yaml raw_roots")
    if missing:
        raise SetupError(f"raw root(s) {', '.join(missing)} in config/local.yaml have no mount "
                         "in LABPIPE_ROOT_PATHS (the container was started without them): "
                         "`labpipe container start` after fixing raw_roots")
    return [{**root, "path": mapping[root["id"]]} for root in roots]


# The lab's own files in config/ (the rest of config/*.yaml are labpipe's defaults, from the code).
LAB_CONFIG_FILES = ("local.yaml", "lab.yaml", "samples.yaml", "sample_ids.yaml", "ignore.yaml")


def default_config_files(code_root: Path | None = None) -> list[Path]:
    """labpipe's defaults: config/*.yaml of the code, without the lab's own files."""
    return sorted(p for p in (Path(code_root or CODE_ROOT) / "config").glob("*.yaml")
                  if p.name not in LAB_CONFIG_FILES)


def load_pipeline_config(project: Path | None = None) -> dict:
    """config/pipeline.yaml (shared policy, from the code) + config/local.yaml (this machine's
    paths, from the project)."""
    if project is None:
        require_project()
    project = Path(project or PROJECT_ROOT)
    with open(CODE_ROOT / "config" / "pipeline.yaml", encoding="utf-8") as stream:
        config = yaml.safe_load(stream)
    local = project / "config" / "local.yaml"
    if not local.exists():
        raise SetupError("config/local.yaml is missing: run `labpipe init` and edit it to "
                         "point at your (read-only) raw data")
    with open(local, encoding="utf-8") as stream:
        machine = yaml.safe_load(stream) or {}
    config["raw_roots"] = machine.get("raw_roots") or []
    config["protected_paths"] = machine.get("protected_paths") or []
    config["agents"] = machine.get("agents")
    config["automation"] = machine.get("automation")
    if (config["automation"] or {}).get("settle_minutes") is not None:
        config["settle_minutes"] = config["automation"]["settle_minutes"]  # this machine's choice
    mapping = os.environ.get("LABPIPE_ROOT_PATHS")
    if mapping:
        config["raw_roots"] = _map_root_paths(config["raw_roots"], _parse_root_paths(mapping))
        # protected_paths in local.yaml are host paths; they do not exist in the container,
        # whose raw data is mounted read-only (the kernel enforces it).
        config["protected_paths"] = []
    override = os.environ.get("LABPIPE_RAW_ROOT")
    if override:
        # Same data, another path: keep the configured id (if there is exactly one root)
        # so manifest entries stay the same when the override is dropped later.
        configured = config["raw_roots"]
        root_id = configured[0]["id"] if len(configured) == 1 else "override"
        config["raw_roots"] = [{"id": root_id, "path": override,
                                "note": "LABPIPE_RAW_ROOT override"}]
    return config


def set_local_block(name: str, value: Any) -> None:
    """Replace the top-level `name:` block of config/local.yaml in place (append it if
    absent). Other blocks and comments between blocks are kept; comments inside the
    replaced block are not. Used by the interactive setup commands, never by agents."""
    path = PROJECT_ROOT / "config" / "local.yaml"
    lines = path.read_text(encoding="utf-8").splitlines()
    start = next((i for i, line in enumerate(lines) if line.startswith(f"{name}:")), None)
    block = yaml.safe_dump({name: value}, sort_keys=False, allow_unicode=True,
                           width=1000).splitlines()
    if start is None:
        lines = [*lines, *block]
    else:
        end = start + 1
        while end < len(lines) and (not lines[end].strip() or lines[end][0].isspace()):
            end += 1
        while end > start + 1 and not lines[end - 1].strip():
            end -= 1  # keep blank lines that separate blocks
        lines[start:end] = block
    atomic_write_text(path, "\n".join(lines).rstrip() + "\n", pipeline=False)


def _resolved(path: Path | str) -> Path:
    return Path(os.path.realpath(path))


def protected_roots(config: dict | None = None) -> list[Path]:
    if config is None:
        try:
            config = load_pipeline_config()
        except SetupError:  # no local.yaml yet: nothing is configured as protected
            return []
    roots = [_resolved(item["path"]) for item in config.get("raw_roots", [])]
    roots += [_resolved(os.path.expanduser(item)) for item in config.get("protected_paths", [])]
    return roots


def _inside(path: Path, root: Path) -> bool:
    return path == root or root in path.parents


def assert_not_protected(path: Path | str, config: dict | None = None) -> Path:
    target = _resolved(path)
    for root in protected_roots(config):
        if _inside(target, root):
            raise UnsafePathError(f"refusing to write inside protected path {root}: {target}")
    return target


def assert_pipeline_writable(path: Path | str, config: dict | None = None) -> Path:
    config = config or load_pipeline_config()
    target = assert_not_protected(path, config)
    allowed = [_resolved(PROJECT_ROOT / config["analysis_dir"]),
               _resolved(PROJECT_ROOT / config["logs_dir"])]
    manifest = _resolved(PROJECT_ROOT / config["manifest"])
    if target == manifest:
        return target
    if any(_inside(target, root) for root in allowed):
        return target
    raise UnsafePathError(f"pipeline may only write under analysis/, logs/ or the manifest: "
                          f"{target}")


def atomic_write_bytes(path: Path, data: bytes, config: dict | None = None,
                       *, pipeline: bool = True) -> None:
    target = (assert_pipeline_writable(path, config) if pipeline
              else assert_not_protected(path, config))
    target.parent.mkdir(parents=True, exist_ok=True)
    handle, temporary = tempfile.mkstemp(prefix=f".{target.name}.", dir=target.parent)
    try:
        with os.fdopen(handle, "wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, target)
    except BaseException:
        if os.path.exists(temporary):
            os.unlink(temporary)
        raise


def atomic_write_text(path: Path, text: str, config: dict | None = None,
                      *, pipeline: bool = True) -> None:
    atomic_write_bytes(path, text.encode("utf-8"), config, pipeline=pipeline)
